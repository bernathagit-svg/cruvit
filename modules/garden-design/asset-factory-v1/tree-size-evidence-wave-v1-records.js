function rec(partial) {
  const row = {
    contract: TREE_SIZE_EVIDENCE_WAVE_VERSION,
    architectureMode: 'tree',
    growthStage: 'mature',
    identityScope: ID,
    heightMinM: null,
    heightMaxM: null,
    spreadMinM: null,
    spreadMaxM: null,
    inferredDimension: false,
    productionCatalogWritten: false,
    mayDrivePhysicalMeterPreview: true,
    provenanceVersion: TREE_SIZE_EVIDENCE_WAVE_VERSION,
    provenanceTimestamp: '2026-09-19',
    ...partial
  };
  if (row.heightMinM != null || row.heightMaxM != null || row.spreadMinM != null || row.spreadMaxM != null) {
    row.normalizedSi = {
      heightM: { min: row.heightMinM ?? null, max: row.heightMaxM ?? null },
      spreadM: { min: row.spreadMinM ?? null, max: row.spreadMaxM ?? null }
    };
  } else if (!('normalizedSi' in row)) {
    row.normalizedSi = null;
  }
  return Object.freeze(row);
}

