/**
 * Garden Tasks Persistence V1 — pure contract helpers (no DOM / network).
 * Authoritative task rows belong to garden_profiles via garden_tasks.
 *
 * My Garden task row shape (normalizeTaskRow):
 * [0] icon, [1] title, [2] when_label, [3] priority, [4] iso/due_on,
 * [5] auto, [6] plantName|weatherKey, [7] done, [8] client_instance_id
 * `.id` mirrors [8] for convenience; index 8 survives JSON localStorage.
 */

export const GARDEN_TASK_PRIORITIES = Object.freeze(['High', 'Medium', 'Low']);
export const TASK_DONE_IDX = 7;
export const TASK_CLIENT_ID_IDX = 8;

export function isValidTaskPriority(priority) {
  return GARDEN_TASK_PRIORITIES.includes(String(priority || '').trim());
}

export function normalizeTaskIso(value) {
  const s = String(value || '').trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(s) ? s : null;
}

/**
 * Ensure a stable client_instance_id on a task row (index 8 + `.id`).
 * Does not invent title/due/priority — only identity for sync.
 */
export function ensureTaskClientId(task, idFactory) {
  const row = Array.isArray(task) ? task : null;
  if (!row) return '';
  while (row.length <= TASK_CLIENT_ID_IDX) row.push(undefined);
  const existing = String(
    row[TASK_CLIENT_ID_IDX] || row.id || row.client_instance_id || ''
  ).trim();
  if (existing) {
    row[TASK_CLIENT_ID_IDX] = existing;
    row.id = existing;
    return existing;
  }
  const makeId =
    typeof idFactory === 'function'
      ? idFactory
      : () => `task_${Date.now()}_${Math.random().toString(36).slice(2, 10)}`;
  const id = String(makeId() || '').trim();
  if (!id) throw new Error('client_instance_id is required');
  row[TASK_CLIENT_ID_IDX] = id;
  row.id = id;
  return id;
}

/**
 * Build server write payload from a My Garden task row, or throw.
 * Does not persist events, credits, catalog care templates, or climate results.
 */
export function buildServerTaskPayload(task, options = {}) {
  const row = Array.isArray(task)
    ? task.slice()
    : task && typeof task === 'object'
      ? [
          task.icon || '🌿',
          task.title || task.name || 'Garden care',
          task.when || task.when_label || task.date || 'This week',
          task.priority || 'Low',
          task.iso || task.due_on || '',
          task.auto ?? task.auto_generated ?? false,
          task.plantName || task.plant_name || '',
          !!task.done,
          task.id || task.client_instance_id || ''
        ]
      : null;
  if (!row) throw new Error('task row is required');

  while (row.length <= TASK_CLIENT_ID_IDX) row.push(undefined);
  if (Array.isArray(task)) {
    if (task.id) row.id = task.id;
    if (task[TASK_CLIENT_ID_IDX]) row[TASK_CLIENT_ID_IDX] = task[TASK_CLIENT_ID_IDX];
  }
  if (task && typeof task === 'object' && !Array.isArray(task) && task.id) {
    row.id = task.id;
    row[TASK_CLIENT_ID_IDX] = task.id;
  }

  const clientInstanceId = ensureTaskClientId(row, options.idFactory);
  if (Array.isArray(task)) {
    while (task.length <= TASK_CLIENT_ID_IDX) task.push(undefined);
    task[TASK_CLIENT_ID_IDX] = clientInstanceId;
    task.id = clientInstanceId;
  }
  const title = String(row[1] || '').trim();
  const icon = String(row[0] || '🌿').trim() || '🌿';
  const whenLabel = String(row[2] || 'This week').trim() || 'This week';
  let priority = String(row[3] || 'Low').trim() || 'Low';
  if (!isValidTaskPriority(priority)) priority = 'Low';
  const dueOn = normalizeTaskIso(row[4]);
  const autoGenerated = row[5] === true;
  const plantNameRaw = String(row[6] || '').trim();
  const plantName = plantNameRaw || null;
  const done = row[TASK_DONE_IDX] === true;
  const gardenPlantId =
    options.gardenPlantId != null && String(options.gardenPlantId).trim()
      ? String(options.gardenPlantId).trim()
      : task?.gardenPlantId || task?.garden_plant_id || null;

  if (!clientInstanceId) throw new Error('client_instance_id is required');
  if (!title) throw new Error('task title is required');

  return {
    client_instance_id: clientInstanceId,
    garden_plant_id: gardenPlantId ? String(gardenPlantId) : null,
    icon,
    title,
    when_label: whenLabel,
    priority,
    due_on: dueOn,
    auto_generated: autoGenerated,
    plant_name: plantName,
    done
  };
}

export function serverTaskToAppTask(row) {
  if (!row || typeof row !== 'object') return null;
  const clientId = String(row.client_instance_id || '').trim();
  if (!clientId) return null;
  const title = String(row.title || '').trim();
  if (!title) return null;
  const priority = isValidTaskPriority(row.priority) ? String(row.priority) : 'Low';
  const dueOn = normalizeTaskIso(row.due_on) || '';
  const task = [
    String(row.icon || '🌿').trim() || '🌿',
    title,
    String(row.when_label || 'This week').trim() || 'This week',
    priority,
    dueOn,
    row.auto_generated === true,
    row.plant_name ? String(row.plant_name) : '',
    row.done === true,
    clientId
  ];
  task.id = clientId;
  if (row.id) task.serverId = row.id;
  if (row.garden_plant_id) task.gardenPlantId = row.garden_plant_id;
  return task;
}

export function mayWriteLegacyLocalTasksToServer(explicitUserConfirm) {
  return explicitUserConfirm === true;
}

export function decideAuthBoundaryTasksRelease(hasLocalSnapshot) {
  return hasLocalSnapshot ? 'restore-snapshot' : 'noop-preserve-local';
}

/**
 * Stale hydration guard: reject task list apply when session/user/active garden drifted.
 */
export function shouldAcceptTaskHydration(
  requestUserId,
  requestGardenId,
  currentSession,
  activeGardenId
) {
  const sessionUserId = currentSession?.user?.id;
  if (!requestUserId || !sessionUserId) return false;
  if (String(requestUserId) !== String(sessionUserId)) return false;
  if (!requestGardenId || !activeGardenId) return false;
  if (String(requestGardenId) !== String(activeGardenId)) return false;
  return true;
}

/**
 * Simulate catalog/care enrichment that must NOT overwrite instance state.
 * Used by regression tests (analogous to Plants V1 status/mark discipline).
 */
export function restoreAuthoritativeTaskInstanceFields(enriched, authoritative) {
  const a = Array.isArray(authoritative) ? authoritative : null;
  const e = Array.isArray(enriched) ? enriched.slice() : null;
  if (!a || !e) return e;
  while (e.length <= TASK_CLIENT_ID_IDX) e.push(undefined);
  e[0] = a[0];
  e[1] = a[1];
  e[2] = a[2];
  e[3] = a[3];
  e[4] = a[4];
  e[5] = a[5];
  e[6] = a[6];
  e[TASK_DONE_IDX] = a[TASK_DONE_IDX];
  e[TASK_CLIENT_ID_IDX] = a[TASK_CLIENT_ID_IDX] || a.id;
  if (a.id) e.id = a.id;
  return e;
}
