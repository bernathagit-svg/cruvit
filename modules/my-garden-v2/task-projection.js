import {
  taskState,
  plantTasks,
  gardenTasks,
  pendingGardenTasks,
  attentionTasks,
  assertSameTaskIdentity,
} from './read-model.js';
import { indexUniqueById } from './plant-instance-projection.js';

function dateOnly(value) {
  if (value == null) return null;
  const s = String(value);
  const m = /^(\d{4}-\d{2}-\d{2})/.exec(s);
  if (!m) throw new Error('invalid_task_due_date:' + s);
  return m[1];
}

function canonicalTaskRow(task, plantsById) {
  const plantId = task.garden_plant_id ?? task.plant_instance_id ?? null;
  const plant = plantId ? plantsById.get(plantId) ?? null : null;

  return Object.freeze({
    id: task.id,
    plantId,
    plantName: plant?.name ?? task.plant_name ?? null,
    title: task.title ?? null,
    dueOn: dateOnly(task.due_on ?? task.due_at ?? task.dueOn),
    state: taskState(task),
    priority: task.priority ?? null,
    taskType: task.task_type ?? task.taskType ?? null,
    sourceModule: task.source_module ?? task.sourceModule ?? null,
    autoGenerated: task.auto_generated === true,
    raw: task,
  });
}

function projectRows(tasks, plants) {
  const plantsById = indexUniqueById(plants, 'plant');
  return tasks.map((task) => canonicalTaskRow(task, plantsById));
}

export function buildPlantScheduleProjection({
  plantId,
  plants = [],
  tasks = [],
} = {}) {
  const rows = projectRows(plantTasks(tasks, plantId), plants);
  return Object.freeze({
    plantId,
    rows: Object.freeze(rows),
  });
}

export function buildUpcomingProjection({
  plants = [],
  tasks = [],
} = {}) {
  const rows = projectRows(gardenTasks(tasks, plants), plants);
  return Object.freeze({
    rows: Object.freeze(rows),
    pending: Object.freeze(rows.filter((row) => row.state === 'pending')),
    completed: Object.freeze(rows.filter((row) => row.state === 'completed')),
    cancelled: Object.freeze(rows.filter((row) => row.state === 'cancelled')),
  });
}

export function buildCalendarProjection({
  plants = [],
  tasks = [],
} = {}) {
  const upcoming = buildUpcomingProjection({ plants, tasks });
  const byDate = new Map();

  for (const row of upcoming.rows) {
    if (!row.dueOn) continue;
    if (!byDate.has(row.dueOn)) byDate.set(row.dueOn, []);
    byDate.get(row.dueOn).push(row);
  }

  return Object.freeze({
    rows: upcoming.rows,
    byDate,
  });
}

export function buildNotificationsProjection({
  plants = [],
  tasks = [],
  today,
} = {}) {
  const sourceRows = attentionTasks(tasks, plants, today);
  const rows = projectRows(sourceRows, plants);

  return Object.freeze({
    rows: Object.freeze(rows),
    overdue: Object.freeze(rows.filter((row) => row.dueOn < today)),
    dueToday: Object.freeze(rows.filter((row) => row.dueOn === today)),
  });
}

export function buildPendingTaskIds({ plants = [], tasks = [] } = {}) {
  return Object.freeze(pendingGardenTasks(tasks, plants).map((task) => task.id));
}

export function assertTaskViewsConsistent({
  plantId,
  plants = [],
  tasks = [],
  today,
} = {}) {
  const schedule = buildPlantScheduleProjection({ plantId, plants, tasks });
  const upcoming = buildUpcomingProjection({ plants, tasks });
  const notifications = buildNotificationsProjection({ plants, tasks, today });

  assertSameTaskIdentity({
    schedule: schedule.rows.map((row) => row.raw),
    upcoming: upcoming.rows.map((row) => row.raw),
    notifications: notifications.rows.map((row) => row.raw),
  });

  const projected = new Map();
  for (const [view, rows] of Object.entries({
    schedule: schedule.rows,
    upcoming: upcoming.rows,
    notifications: notifications.rows,
  })) {
    for (const row of rows) {
      const fingerprint = JSON.stringify({
        plantId: row.plantId,
        title: row.title,
        dueOn: row.dueOn,
        state: row.state,
      });
      if (!projected.has(row.id)) projected.set(row.id, { view, fingerprint });
      else if (projected.get(row.id).fingerprint !== fingerprint) {
        throw new Error(
          'task_view_projection_conflict:' +
          row.id + ':' +
          projected.get(row.id).view + ':' +
          view
        );
      }
    }
  }

  return true;
}
